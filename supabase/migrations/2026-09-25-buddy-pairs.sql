-- ============================================================================
-- БАДИ-ПАРЫ СОБЫТИЯ
--
-- Правило «Бади» участники принимают на входе в клуб (src/data/clubRules.ts,
-- Правила_участника.pdf): у каждого на событии есть напарник, который держит
-- его в поле зрения от сбора до разъезда. Правило было, самих пар — нет:
-- человек принимал обязательство, но так и не узнавал, за кого он отвечает.
-- Эта таблица и есть недостающая половина.
--
-- Модель: одна строка на участника события, pair_id — общий ключ связки.
-- Связка это 2 человека, а при нечётном составе — 3 (никого не бросаем
-- одного). «Мой бади» = остальные участники моей связки.
--
-- Пары НЕ пересобираются при каждой записи: у кого напарник уже есть — он
-- не меняется. Новые люди встают в пару друг с другом, а последний нечётный
-- подсаживается третьим. Так человек не узнаёт за день до выезда, что его
-- бади теперь кто-то другой.
--
-- Идемпотентно: повторный запуск безвреден.
-- ============================================================================

CREATE TABLE IF NOT EXISTS event_buddies (
  id BIGSERIAL PRIMARY KEY,
  event_id TEXT NOT NULL,
  telegram_id BIGINT NOT NULL,
  -- Общий ключ связки: у бади он одинаковый.
  pair_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Когда человеку сообщили, кто его бади. NULL = объявить при ближайшем кроне.
  -- Сбрасывается в NULL, когда состав связки изменился.
  notified_at TIMESTAMPTZ,
  UNIQUE (event_id, telegram_id)
);

CREATE INDEX IF NOT EXISTS idx_event_buddies_event ON event_buddies(event_id);
CREATE INDEX IF NOT EXISTS idx_event_buddies_pair ON event_buddies(event_id, pair_id);

-- RLS как на всех таблицах: сервер ходит под service_role (BYPASSRLS),
-- анонимный доступ через PostgREST закрыт (см. 2026-enable-rls-all.sql).
ALTER TABLE event_buddies ENABLE ROW LEVEL SECURITY;
