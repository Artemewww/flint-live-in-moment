import { CommunityEvent } from './types';

/**
 * Авто-гайд под событие: что взять с собой, почасовая программа и вектор
 * «Дома Личности» — генерируются по типу события и ключевым словам названия,
 * если организатор не задал своё. Цель — «мировой уровень» подачи без ручной работы.
 */

export interface EventGuide {
  bring: string[];      // что взять с собой
  program: string[];    // программа (по шагам/времени)
  vector: { title: string; text: string }; // вектор Дома Личности + почему уместно
}

function has(event: CommunityEvent, ...words: string[]): boolean {
  const s = `${event.title} ${event.description || ''} ${event.painPoint || ''}`.toLowerCase();
  return words.some((w) => s.includes(w));
}

const VECTORS = {
  wall: { title: 'Воля (Стены) — Мужской дух', text: 'Плавим телесные зажимы и городские маски, закаляем характер честным кругом лицом к лицу.' },
  roof: { title: 'Совесть (Крыша) — Интеллект', text: 'Тренируем критическое мышление и глубину, избавляемся от чужих клише и шаблонов.' },
  heat: { title: 'Любовь (Тепло) — Союз', text: 'Живая встреча людей, искренность и поддержка, тёплые человеческие связи без масок.' },
  life: { title: 'Счастье (Бытие) — Присутствие', text: 'Возвращаемся в тело и момент, чистый воздух и движение вместо шума мегаполиса.' },
  foundation: { title: 'Предназначение (Фундамент)', text: 'Сверяемся с собой и своими ориентирами, находим опору и смысл среди своих.' },
};

/** Что взять с собой. */
function bringList(event: CommunityEvent): string[] {
  if (has(event, 'баня', 'парен', 'пар ')) {
    return [
      'Личный веник (дуб/берёза)',
      'Шапка для бани и тапки',
      'Сменная одежда, полотенце',
      'Масла / соль / скраб для парной — по желанию',
      'Вода, травяной чай',
      'Угощение на общий стол — по желанию',
      'Открытость и хорошее настроение',
    ];
  }
  if (has(event, 'кемпинг', 'палат', 'слёт', 'слет')) {
    return ['Палатка и спальник', 'Каремат (коврик)', 'Тёплая одежда, дождевик', 'Фонарик', 'Своя посуда и кружка', 'Продукты в общий котёл', 'Хорошее настроение'];
  }
  if (has(event, 'поход', 'трек', 'ислоч', 'пуща')) {
    return ['Удобная обувь', 'Вода и перекус', 'Дождевик', 'Походная кружка', 'Пауэрбанк', 'Хорошее настроение'];
  }
  if (has(event, 'сплав', 'каяк', 'байдар')) {
    return ['Спасжилет (уточни у организатора)', 'Сменная одежда в гермопакете', 'Обувь, которую не жалко', 'Вода, перекус', 'Солнцезащита'];
  }
  if (event.type === 'intellectual') {
    return ['Заряженный ум и любопытство', 'Блокнот — по желанию', 'Вкусняшка к чаю — по желанию'];
  }
  return ['Удобная одежда', 'Вода', 'Угощение на общий стол — по желанию', 'Открытость и хорошее настроение'];
}

/** Программа по шагам (если организатор не задал свою). */
function defaultProgram(event: CommunityEvent): string[] {
  if (has(event, 'баня', 'парен')) {
    return [
      'Сбор, знакомство, травяной чай',
      'Разогрев, первый мягкий заход',
      'Парение вениками',
      'Ледяная купель / контраст',
      'Дыхательная практика (по методу Вима Хофа)',
      'Отдых, чай, лёгкое угощение',
      'Круг честных разговоров у камина',
      'Завершение, обмен впечатлениями',
    ];
  }
  if (has(event, 'поход', 'трек', 'кемпинг', 'слёт', 'слет')) {
    return ['Сбор, выезд/старт', 'Переход по маршруту', 'Привал, перекус', 'Основная активность', 'Ужин у костра', 'Песни, честный круг', 'Завершение'];
  }
  if (event.type === 'intellectual') {
    return ['Сбор, знакомство', 'Основная часть (разбор/игра)', 'Глубокая дискуссия', 'Чай, общение', 'Итоги'];
  }
  if (event.type === 'active') {
    return ['Сбор, разминка', 'Основная активность', 'Заминка, восстановление', 'Чай, общение'];
  }
  return ['Сбор и знакомство', 'Основная часть', 'Тёплое общение', 'Завершение'];
}

function vectorFor(event: CommunityEvent): { title: string; text: string } {
  if (has(event, 'баня', 'парен')) return VECTORS.wall;
  if (event.type === 'male') return VECTORS.wall;
  if (event.type === 'intellectual') return VECTORS.roof;
  if (event.type === 'active') return VECTORS.life;
  if (event.type === 'mixed') return VECTORS.heat;
  return VECTORS.foundation;
}

export function getEventGuide(event: CommunityEvent): EventGuide {
  const program = Array.isArray(event.program) && event.program.length > 0
    ? (event.program as string[])
    : defaultProgram(event);
  return { bring: bringList(event), program, vector: vectorFor(event) };
}
