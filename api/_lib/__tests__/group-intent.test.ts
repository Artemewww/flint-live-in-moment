import { rideIntent, isAddressedToPerson } from '../group-intent';

describe('rideIntent — просьба о месте', () => {
  it('ловит фразу, на которой бот промолчал в чате Bison Race', () => {
    // Дословно из чата 25.09.2026, 15:11. Ни один прежний паттерн не сработал.
    expect(rideIntent('Я просто с женой хотел, если можно нас куда-нибудь подкинуть, на бенз скинемся ❤️')).toBe('need');
  });

  it.each([
    'Нужна попутка из Малиновки',
    'ребята, подвезите кто-нибудь, я без машины',
    'Я не на чем, можно с кем-то поехать?',
    'Есть место для нас двоих?',
    'кто подбросит до Несвижа?',
    'заберите меня по пути, пожалуйста',
    'ищу попутку на субботу',
  ])('«%s» → просьба', (text) => {
    expect(rideIntent(text)).toBe('need');
  });
});

describe('rideIntent — предложение подвезти', () => {
  it.each([
    'Еду на своей, подвезу двоих',
    'беру каршеринг, 3 места, выезжаю в 5',
    'заберу по пути, пишите в личку',
    'я на машине, могу взять двоих',
  ])('«%s» → предложение, а не просьба', (text) => {
    expect(rideIntent(text)).toBe('offer');
  });

  it('«подвезу» и «подвезите» не путаются — одна буква, разный смысл', () => {
    expect(rideIntent('подвезу двоих от Боровой, пишите')).toBe('offer');
    expect(rideIntent('подвезите меня, пожалуйста, я без машины')).toBe('need');
  });
});

describe('rideIntent — бот не влезает без нужды', () => {
  it.each([
    'Отлично. Топ!',
    'я возьму горелку и котелок',
    'Всем привет, готовимся',
  ])('«%s» → мимо', (text) => {
    expect(rideIntent(text)).toBe('none');
  });

  it('вопрос про места остаётся вопросом, а не заявкой', () => {
    expect(rideIntent('У кого есть места в машине?')).toBe('question');
  });

  it('короткие реплики не считаются заявкой', () => {
    expect(rideIntent('подкинь')).toBe('none');
  });
});

describe('isAddressedToPerson — бот не влезает в чужой разговор', () => {
  it('«А ты где живёшь?» — вопрос Егору, а не боту', () => {
    // Живой случай 25.09.2026, 15:33. Бот ответил «в данных поездки не указано
    // место проживания Егора» — вопрос был не к нему, ответ бесполезный.
    expect(isAddressedToPerson('А ты где живешь?')).toBe(true);
  });

  it.each([
    'Даня, ты выехал?',
    'у тебя есть место?',
    'твоя машина на ходу?',
  ])('«%s» → человеку', (text) => {
    expect(isAddressedToPerson(text)).toBe(true);
  });

  it.each([
    'Во сколько выезд?',
    'Где сбор?',
    'Сколько стоит участие?',
    'Что брать с собой?',
  ])('«%s» → боту, отвечаем', (text) => {
    expect(isAddressedToPerson(text)).toBe(false);
  });
});

describe('rideIntent — предложение забрать', () => {
  it('«С метро Уручье могу забрать вас» — предложение, а не пустое место', () => {
    // Живой случай 25.09.2026, 15:53. Раньше carOffer знал «заберу», но не
    // «могу забрать», и новая точка старта в машину не попадала.
    expect(rideIntent('С метро Уручье могу забрать вас')).toBe('offer');
  });

  it('«захвачу по пути» — предложение, «захвати меня» — просьба', () => {
    expect(rideIntent('захвачу по пути, пишите в личку')).toBe('offer');
    expect(rideIntent('захвати меня по пути, пожалуйста')).toBe('need');
  });

  it.each([
    'могу подвезти двоих от Уручья',
    'могу подбросить до Несвижа',
    'могу подкинуть вас от метро',
  ])('«%s» → спорно, решает ИИ', (text) => {
    // Слово из просьбы, смысл предложения. Регулярка тут честно бессильна:
    // в webhook.ts такие уходят к ИИ, и после ответа «не просьба» бюджет
    // возвращается, чтобы сообщение разобрал блок «машина из чата».
    expect(rideIntent(text)).toBe('ambiguous');
  });
});
