import { rideIntent } from '../group-intent';

describe('rideIntent — просьба о месте', () => {
  it('ловит фразу, на которой бот промолчал в чате Bison Race', () => {
    // Дословно из чата 25.09.2026, 15:11. Ни один прежний паттерн не сработал.
    expect(rideIntent('Я просто с женой хотел, если можно нас куда-нибудь подкинуть, на бенз скинемся ❤️')).toBe('need');
  });

  it.each([
    'Нужна попутка из Малиновки',
    'ребята, подвезите кто-нибудь, я без машины',
    'Я не на чем, можно с кем-то поехать?',
    'Есть место для нас двоих?',
    'кто подбросит до Несвижа?',
    'заберите меня по пути, пожалуйста',
    'ищу попутку на субботу',
  ])('«%s» → просьба', (text) => {
    expect(rideIntent(text)).toBe('need');
  });
});

describe('rideIntent — предложение подвезти', () => {
  it.each([
    'Еду на своей, подвезу двоих',
    'беру каршеринг, 3 места, выезжаю в 5',
    'заберу по пути, пишите в личку',
    'я на машине, могу взять двоих',
  ])('«%s» → предложение, а не просьба', (text) => {
    expect(rideIntent(text)).toBe('offer');
  });

  it('«подвезу» и «подвезите» не путаются — одна буква, разный смысл', () => {
    expect(rideIntent('подвезу двоих от Боровой, пишите')).toBe('offer');
    expect(rideIntent('подвезите меня, пожалуйста, я без машины')).toBe('need');
  });
});

describe('rideIntent — бот не влезает без нужды', () => {
  it.each([
    'Отлично. Топ!',
    'я возьму горелку и котелок',
    'Всем привет, готовимся',
  ])('«%s» → мимо', (text) => {
    expect(rideIntent(text)).toBe('none');
  });

  it('вопрос про места остаётся вопросом, а не заявкой', () => {
    expect(rideIntent('У кого есть места в машине?')).toBe('question');
  });

  it('короткие реплики не считаются заявкой', () => {
    expect(rideIntent('подкинь')).toBe('none');
  });
});
