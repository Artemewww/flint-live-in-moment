/**
 * РАЗБОР НАМЕРЕНИЯ В ЧАТЕ СОБЫТИЯ: просят место или предлагают его.
 *
 * ⚠️ Эталон под тестами. Рантайм-копии этих выражений задублированы в
 * api/telegram/webhook.ts (блоки 5 и 6 группового обработчика), потому что
 * импорт из api/_lib/ роняет serverless-функции на Vercel в рантайме
 * (FUNCTION_INVOCATION_FAILED, локальные tsc/esbuild это НЕ ловят).
 * Меняешь выражение — правь оба места, тест держит поведение.
 *
 * Зачем тест именно здесь: сломалось ровно это. 25.09.2026 в чате
 * «BISON RACE & FLINT» участник написал «если можно нас куда-нибудь
 * подкинуть» — и бот промолчал, потому что регулярка знала «подвезти», но
 * не знала «подкинуть». Живые формулировки проверяются тестом, а не на
 * людях за два дня до выезда.
 *
 * Регулярка только ОТБИРАЕТ кандидатов, решение принимает ИИ: «подвезу» и
 * «подвезите» отличаются одной буквой и значат противоположное.
 */

/** Просьба о месте: «подкиньте», «нужна попутка», «я без машины». */
export const SEAT_NEED =
  /(?<![а-яёa-z])(подкин|подброс|подбер|захват|заберит|возьмит|нужн[оа]\s+(мест|попутк)|ищ[уе]м?\s+попутк|без\s+машины|не\s+на\s+ч[её]м|поехать\s+с\s+кем|можно\s+с\s+кем|мест[оа]?\s+для\s+(меня|нас)|подвезт|подвезит|подвези|подвез[её]т)/i;

/**
 * Предложение подвезти: «еду на своей», «каршеринг, 3 места».
 * «могу забрать вас» сюда не попадало — было только «заберу». Живой случай:
 * «С метро Уручье могу забрать вас» — человек назвал новую точку старта, а в
 * машине осталась прежняя, и попутчики поехали бы не туда.
 */
export const CAR_OFFER =
  /(?<![а-яёa-z])(каршеринг|каршер|на\s+своей|на\s+машине|на\s+авто|за\s+рулём|за\s+рулем|подвезу|заберу|захвачу|могу\s+(взять|забрать|захватить|подвезти|подбросить|подкинуть))/i;

/**
 * Вопрос адресован человеку, а не боту.
 * Живой случай: «А ты где живёшь?» — Людмила спрашивала Егора, а бот влез с
 * «в данных поездки не указано место проживания Егора». Доверие к боту в чате
 * тратится быстро: после пары таких ответов его перестают читать.
 * В оргвопросе к боту пишут «во сколько выезд», а не «ты где».
 */
export function isAddressedToPerson(text: string): boolean {
  const s = String(text || '');
  return /^@?[А-ЯЁ][а-яё]{2,}\s*[,!]/.test(s.trim())
    || /(?<![а-яёa-z])(ты|тебя|тебе|тобой|твой|твоя|твои|тво[ёе])(?![а-яёa-z])/i.test(s);
}

/** Вопрос про свободные места, на который бот отвечает прямо из базы. */
export const RIDE_QUESTION =
  /(у\s+кого\s+(есть|будут?)\s+мест|есть\s+ли\s+(свободн[а-яё]*\s+)?мест|свободн[а-яё]*\s+мест\s+(в|на)\s+машин|мест[оа]?\s+в\s+машин|кто[- ]нибудь\s+едет\s+(на\s+машин|на\s+авто)|кто\s+едет\s+на\s+машин|нужна\s+попутк|можно\s+подвез)/i;

export type RideIntent = 'need' | 'offer' | 'ambiguous' | 'question' | 'none';

/**
 * К какому блоку группового обработчика уйдёт сообщение.
 * Порядок повторяет webhook.ts: просьба разбирается РАНЬШЕ предложения,
 * иначе «подвезите, я без машины» уедет в ветку «заводим машину».
 *
 * 'ambiguous' — сработали оба паттерна, и по словам не отличить: «могу
 * подкинуть вас от метро» это предложение, хотя слово «подкинуть» стоит в
 * просьбе. Решает ИИ. В webhook.ts это и есть ветка, где после ответа «не
 * просьба» бюджет вызова возвращается и сообщение уходит разбору машины —
 * без неё предложение терялось бы молча.
 */
export function rideIntent(text: string): RideIntent {
  const s = String(text || '');
  const need = SEAT_NEED.test(s) && s.length > 10;
  const offer = CAR_OFFER.test(s) && s.length > 12 && !s.trim().endsWith('?');
  if (need && offer) return 'ambiguous';
  if (need) return 'need';
  if (offer) return 'offer';
  if (RIDE_QUESTION.test(s)) return 'question';
  return 'none';
}
